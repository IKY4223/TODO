"""Names and talent ids the Enka response only refers to by id.

gamedata.json is generated by scripts/sync_gamedata.py.
"""

from pathlib import Path

from pydantic import BaseModel

from app.showcase.models import Element


class CharacterData(BaseModel):
    name: str
    element: Element | None
    icon: str
    talents: list[tuple[int, int]]  # (talent id, id constellations boost it by), in display order


class GameData(BaseModel):
    characters: dict[str, CharacterData]
    weapons: dict[str, str]
    sets: dict[str, str]


GAMEDATA = GameData.model_validate_json((Path(__file__).parent / "gamedata.json").read_bytes())
