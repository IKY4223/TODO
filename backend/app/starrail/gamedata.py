"""Names, icons and stat tables the Enka response only refers to by id.

gamedata.json and texts.json are generated by scripts/sync_starrail_data.py.
"""

from pathlib import Path

from pydantic import BaseModel

from app.starrail.models import Language, SkillKind


class CharacterData(BaseModel):
    name: dict[str, str]  # language -> name
    rarity: int
    element: str
    path: str
    icon: str
    # One entry per eidolon: skill tree point (its id's last three digits) -> levels added.
    eidolons: list[dict[int, int]]


class LightConeData(BaseModel):
    name: dict[str, str]
    rarity: int
    icon: str


class RelicData(BaseModel):
    slot: str
    set: int
    rarity: int
    main_group: int
    sub_group: int
    icon: str


class GameData(BaseModel):
    characters: dict[str, CharacterData]
    profile_icons: dict[str, str]
    light_cones: dict[str, LightConeData]
    relics: dict[str, RelicData]
    sets: dict[str, dict[str, str]]
    # group -> affix id -> (property, base value, value added per level)
    main_affixes: dict[str, dict[str, tuple[str, float, float]]]
    # group -> affix id -> (property, value per roll, value added per roll step)
    sub_affixes: dict[str, dict[str, tuple[str, float, float]]]


GAMEDATA = GameData.model_validate_json((Path(__file__).parent / "gamedata.json").read_bytes())


class SkillText(BaseModel):
    kind: SkillKind | None  # None for a skill without a level, such as the technique
    label: str  # the skill's type in the text's language: "Basic ATK"
    name: str
    # "#1[i]%" stands for the first number of the level's params, whole, as a percent.
    description: str
    params: list[list[float]]  # one list of numbers per level


class EidolonText(BaseModel):
    name: str
    description: str


class TraceText(BaseModel):
    id: int  # the point's id in the showcase's skill tree
    name: str
    skill: bool  # True for a point that levels a skill, False for a bonus ability or a stat
    description: str  # with "#1[i]%" placeholders, like a skill's
    params: list[float]


class CharacterTexts(BaseModel):
    skills: list[SkillText]
    traces: list[TraceText]
    eidolons: list[EidolonText]


class Texts(BaseModel):
    languages: dict[Language, dict[str, CharacterTexts]]
    # trace point -> for each of its levels, item id -> amount
    costs: dict[str, list[dict[str, int]]]
    items: dict[Language, dict[str, str]]  # item id -> name


TEXTS = Texts.model_validate_json((Path(__file__).parent / "texts.json").read_bytes())
