"""Print the input limits as a TypeScript module.

The frontend guides input with the very numbers the API validates against, so the two
cannot drift apart. `npm run gen:api` writes the output to frontend/src/api/limits.ts.
"""

import json

from app.damage import api as damage
from app.showcase import api as showcase
from app.wishes import api as wishes
from app.wishes.engine import GENSHIN_CHARACTER

LIMITS: dict[str, int | str] = {
    "MAX_PITY": GENSHIN_CHARACTER.hard_pity - 1,
    "MAX_COPIES": wishes.MAX_COPIES,
    "MAX_PULLS": wishes.MAX_PULLS,
    "UID_PATTERN": showcase.UID_PATTERN,
    "MAX_MULTIPLIER": damage.MAX_MULTIPLIER,
    "MAX_ENEMY_LEVEL": damage.MAX_ENEMY_LEVEL,
    "MIN_RESISTANCE": damage.MIN_RESISTANCE,
    "MAX_RESISTANCE": damage.MAX_RESISTANCE,
}


def render() -> str:
    lines = ["// Generated by backend/app/limits.py from the API's validation limits. Do not edit."]
    lines += [f"export const {name} = {json.dumps(value)}" for name, value in LIMITS.items()]
    return "\n".join(lines)


if __name__ == "__main__":
    print(render())
